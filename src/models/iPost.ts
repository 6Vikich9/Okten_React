// Модель поста
export interface IPost
{
    // Унікальний номер поста. Потрібен як key і для звʼязку з коментарями (comment.postId === post.id)
    id: number;
    // Номер юзера-автора. За ним на /complex розкладаємо пости по юзерах
    userId: number;
    // Заголовок поста — його показуємо
    title: string;
    // Текст поста (зараз не виводимо, але він приходить від сервера)
    body: string;
}