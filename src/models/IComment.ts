// Модель коментаря
export interface IComment
{
    // Унікальний номер коментаря (key у списку)
    id: number;
    // Номер поста, до якого належить коментар. За ним на /complex підбираємо коментарі до кожного поста
    postId: number;
    // Тема/назва коментаря — її показуємо
    name: string;
    // Текст коментаря (зараз не виводимо)
    body: string;
}