
/* Link — замінює тег <a>: змінює адресу БЕЗ перезавантаження сторінки (атрибут to — куди перейти)
   Outlet — "дірка" в шаблоні: на її місце роутер підставляє сторінку дочірнього маршруту (UsersPage, PostsPage ...) */
import {Link, Outlet} from "react-router";

/* Компонент App — спільний шаблон (layout) для всіх сторінок: меню зверху + змінний вміст знизу.
   Props (аргументів) немає: дужки порожні, бо компонент нічого ззовні не отримує. Тип повернення TS виводить сам (JSX.Element).
   Його рендерить не main.tsx, а роутер: див. router.tsx, маршрут "/" з element: <App/> */
function App()
{
  return (
      // <>...</> — Fragment: порожня обгортка, бо компонент має повернути один кореневий елемент, а ми не хочемо зайвого <div> в DOM
      <>
          {/* nav — семантичний тег для навігації. Всередині Link: атрибут to — шлях маршруту, текст між тегами — що бачить користувач.
          "|" — просто текст-роздільник */}
        <nav>
          <Link to="/users">users</Link> | <Link to="/posts">posts</Link> | <Link
            to="/comments">comments</Link> | <Link to="/complex">complex</Link>
        </nav>
          {/* Outlet — сюди вставляється вміст активного дочірнього маршруту. Меню вище лишається на місці, змінюється тільки це місце */}
        <Outlet/>
      </>
  );
}

// export default — експорт за замовчуванням: при імпорті можна дати будь-яку назву без {} (у router.tsx: import App from ...)
export default App
